function registerSlug(id, name) {
  const base = routing.slug(name);
  let s = base;
  for (let i = 2; slugIndex.toId.has(s); i++) s = `${base}_${i}`;
  slugIndex.toId.set(s, id);
  slugIndex.toSlug.set(id, s);
  return s;
}

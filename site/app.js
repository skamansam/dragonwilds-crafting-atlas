function parseStats(text) {
  const out = {};
  for (const line of String(text).split('\n')) {
    const m = line.match(/^\s*([^:]+?)\s*:\s*(.*?)\s*$/);
    if (m?.[1]) out[m[1]] = m[2];
  }
  return out;
}


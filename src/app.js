// swaps the live toast's text for text + an Undo button (the toast itself is
// pointer-events:none — only the button re-enables pointer events)
function upgradeToastWithUndo() {
  const undo = pendingSettingUndo;
  if (!undo) return;
  pendingSettingUndo = null;
  setTimeout(() => {
    const t = document.getElementById('toast');
    if (!t || !t.classList.contains('show')) return; // already dismissed
    t.innerHTML = '';
    const span = document.createElement('span');
    span.textContent = t.dataset.msg || '';
    const btn = document.createElement('button');
    btn.className = 'toast-undo';
    btn.textContent = 'Undo';
    btn.onclick = () => { clearTimeout(toastTimer); t.classList.remove('show'); undo(); };
    t.append(span, btn);
  }, 0);
}
function runLayout(preset = currentLayout, { skipSaved = false, forceMain = false, reflow = true, visibleOnly = false } = {}) {
  // auto-relayout off: skip automatic graph-change reflows, but explicit user
  // layout requests (algorithm select, density slider/✕, force/anim/saved
  // toggles, recalc, boot) pass reflow:false so they always run
  if (reflow && !autoRelayoutOn()) return;
  // graph-change reflows with nothing shown have nothing to arrange (class-
  // based check: :visible lags the style pass)
  if (visibleOnly && cy.nodes('.hidden').length === cy.nodes().length) return;
  // supersede every in-flight run BEFORE this one touches positions:
  //  · bump the main-thread token — a superseded async layout still calls
  //    layoutPositions when its promise resolves (elk's stop() is a no-op), and
  //    those position WRITES happen before layoutstop, so the handler guard
  //    below cannot stop them; the token-checked transform can
  //  · bump the worker generation and cancel its job — otherwise a late worker
  //    result would land on top of this arrangement
  //  · null activeLayout BEFORE stop(): stop() may emit layoutstop
  //    synchronously, and that must not be mistaken for a completion
  const myRunSeq = ++layoutRunSeq;
  const jobToken = supersedeWorker(); // bump the worker generation + cancel its in-flight job, if any
  const prevLayout = activeLayout;
  activeLayout = null;
  if (prevLayout) { try { prevLayout.stop(); } catch {} }
  stopProgressBar(null, false);
  stopLayoutPill(); // a superseding run owns the Arranging pill from here on
  layoutRunning = true;
  upgradeToastWithUndo(); // a settings flip started this run — give its toast an Undo button
  const make = LAYOUTS[preset] || LAYOUTS['elk-layered-wide'];
  const opts = make();
  // P1.5-1: animation kill-switch — jump straight to the final arrangement
  if (!animateOn) { opts.animate = false; delete opts.animationDuration; delete opts.animationEasing; }
  // P1.5-2: per-preset simulation caps
  const cap = CAPS[preset];
  if (cap) Object.assign(opts, cap);
  // graph-change reflows arrange only what is shown — hidden nodes must not
  // anchor the physics, or filtering would never re-tighten the view. The
  // explicit `eles` overrides any preset default.
  if (visibleOnly) opts.eles = cy.elements(':visible');
  // small visible subgraphs: the preset gaps are tuned for the ~1,900-node map,
  // so a 12-node solo view would lay out at map scale and zoom-to-fit renders
  // specks. Compress the spacing proportionally (floored) below 80 nodes.
  if (visibleOnly && opts.eles) {
    const vn = opts.eles.nodes().length;
    if (vn && vn < 80) {
      const f = Math.max(0.22, Math.pow(vn / 80, 0.65));
      const sc = v => v * f;
      if (opts.nodeSeparation) opts.nodeSeparation = sc(opts.nodeSeparation);
      if (opts.idealEdgeLength) opts.idealEdgeLength = sc(opts.idealEdgeLength);
      if (opts.nodeRepulsion) opts.nodeRepulsion *= f * f; // repulsion is quadratic
      if (opts.nodeSep) opts.nodeSep = sc(opts.nodeSep);
      if (opts.rankSep) opts.rankSep = sc(opts.rankSep);
      if (opts.edgeSep) opts.edgeSep = sc(opts.edgeSep);
      if (typeof opts.spacing === 'number') opts.spacing = sc(opts.spacing);
      if (typeof opts.inLayerSpacingFactor === 'number') opts.inLayerSpacingFactor = Math.max(1, opts.inLayerSpacingFactor * f);
      if (opts.spacingFactor) opts.spacingFactor = Math.max(0.4, opts.spacingFactor * f);
      if (opts.elk) for (const k of Object.keys(opts.elk))
        if (/spacing/i.test(k) && typeof opts.elk[k] === 'number') opts.elk[k] = sc(opts.elk[k]);
    }
  }
  // current spacing — captured for 💾 custom snapshots (P3-1b)
  const curSpacing = opts.elk ? { between: opts.elk['elk.layered.spacing.nodeNodeBetweenLayers'], in: opts.elk['elk.spacing.nodeNode'] } : null;
  lastSpacing = curSpacing || lastSpacing;
  // slider + 💾/✕ only make sense for (or around) the elk layered layouts
  const cl = loadCustomLayouts();
  const hasCustom = !!(cl[densKey(preset)] || cl[preset]);
  const densRelevant = isElkDenseable(preset) || hasCustom;
  const densWrap = document.getElementById('densWrap');
  const saveBtn = document.getElementById('densSave');
  const clearBtn = document.getElementById('densClear');
  if (densWrap) densWrap.classList.toggle('off', !densRelevant);
  if (saveBtn) saveBtn.style.display = densRelevant ? '' : 'none';
  if (clearBtn) clearBtn.style.display = hasCustom ? '' : 'none';
  const saveRow = document.querySelector('.s-save'); // hide the row when every button on it is hidden
  if (saveRow) saveRow.style.display = (densRelevant || hasCustom) ? '' : 'none';
  if (saveBtn) saveBtn.onclick = () => {
    if (!curSpacing) { toast('Open an elk layered layout first — snapshots save its arrangement'); return; }
    pendingSave = { preset, dens: getDensPct() };
    if (layoutRunning) { toast('Arranging — the snapshot is captured the moment the layout settles'); return; }
    const p = pendingSave; pendingSave = null;
    doCustomSave(p.preset, lastSpacing, p.dens); // already settled — capture now
  };
  if (clearBtn) clearBtn.onclick = () => {
    const all = loadCustomLayouts();
    delete all[densKey(preset)];
    delete all[densKey(preset) + '~meta'];
    delete all[preset];
    delete all[preset + '~meta'];
    try { localStorage.setItem('dw.customLayouts', JSON.stringify(all)); } catch {}
    toast(`Custom snapshot cleared for ${preset} @ ${getDensPct()}%`);
    runLayout(preset, { reflow: false, visibleOnly: true });
  };
  // ⤓ share: export the current 💾 snapshot so it can be merged into the
  // site's curated set (scripts/merge-snapshots.mjs)
  const shareBtn = document.getElementById('densShare');
  if (shareBtn) {
    shareBtn.style.display = hasCustom ? '' : 'none';
    shareBtn.onclick = () => shareSnapshot(preset, getDensPct());
  }
  // P1.5-3: precomputed positions — instant, deterministic, no physics
  // precedence: own 💾 snapshot → curated snapshot → bundled manifest
  // an isolated view has no meaningful full-map snapshot: applying bundled or
  // curated positions holds every node where the whole map put it (the visible
  // subtree never re-tightens) and drags the hidden majority along too. Explicit
  // layout selections on an isolated view therefore skip snapshots and recompute
  // on the visible subtree — the same thing graph-change reflows already do.
  const isolatedSkipSaved = skipSaved || (visibleOnly && !!isolatedRoot);
  const customMap = isolatedSkipSaved ? null : (cl[densKey(preset)] || cl[preset] || null);
  const cu = loadCuratedLayouts();
  const curatedMap = (cu[densKey(preset)] || cu[preset] || null);
  let savedMap = (savedToggleOn() && !isolatedSkipSaved && (customMap || curatedMap || (loadSavedLayouts() && loadSavedLayouts()[preset]))) || null;
  if (savedMap && !isSaneSnapshot(savedMap)) {
    if (customMap) {
      const all = loadCustomLayouts();
      delete all[densKey(preset)];
      delete all[densKey(preset) + '~meta'];
      delete all[preset];
      delete all[preset + '~meta'];
      try { localStorage.setItem('dw.customLayouts', JSON.stringify(all)); } catch {}
      toast('Custom snapshot looked degenerate — cleared; recomputing live');
    }
    else if (savedMap === curatedMap) toast('Curated snapshot looked degenerate — skipping it');
    savedMap = null;
  }
  usingSavedPositions = false;
  usingCustomPositions = false;
  usingCuratedPositions = false;
  savedRunHidden = null; // live path: any pending reflow is meaningful again
  const snapNote = document.getElementById('snapshotNote'); // ⚙ status line
  if (savedMap) {
    savedRunHidden = cy.nodes('.hidden').length; // reflows before any change must not supersede this run
    usingSavedPositions = true;
    usingCustomPositions = !!customMap && savedMap === customMap;
    usingCuratedPositions = !!curatedMap && savedMap === curatedMap;
    if (snapNote) snapNote.textContent = 'arrangement: ' + (usingCustomPositions ? 'your saved view (💾)' : usingCuratedPositions ? 'shared curated view' : 'bundled snapshot');
    cy.batch(() => {
      for (const n of cy.nodes()) {
        const p = savedMap[n.id()];
        if (p) n.position({ x: p.x, y: p.y });
      }
      // nodes absent from the snapshot (region pseudo-nodes added after it was
      // captured) sit at the centroid of their laid-out neighbours instead of
      // piling up at the origin
      for (const n of cy.nodes()) {
        if (savedMap[n.id()]) continue;
        const nb = n.neighborhood('node').filter(x => savedMap[x.id()]);
        if (!nb.length) continue;
        let sx = 0, sy = 0;
        nb.forEach(x => { const p = savedMap[x.id()]; sx += p.x; sy += p.y; });
        n.position({ x: Math.round(sx / nb.length), y: Math.round(sy / nb.length) });
      }
    });
    layoutRunning = false;
    stopProgressBar(null, false); // saved path never fires layoutstop — stop the bar here
    recordLayoutDone(layoutElapsed(), cy.nodes(':visible').length); // ⏱ counts too
    setLayoutIndicator(false, `${usingCustomPositions ? 'custom' : usingCuratedPositions ? 'curated' : 'saved'} · ${preset}`); // brief flash
    setTimeout(() => { if (!layoutRunning) setLayoutIndicator(false); }, 1200);
    hideVeil();
    if (!isolatedRoot) cy.fit(undefined, 60);
    updateReadout();
    return;
  }
  if (snapNote) snapNote.textContent = (visibleOnly && isolatedRoot)
    ? 'live-computed (isolated view — snapshot skipped)'
    : 'live-computed (no snapshot applied)';
  // P1-2 worker spike: compute off-thread, apply positions in one batch. The
  // page keeps animating/panning while physics chews in the background.
  // Supersede: a newer runLayout bumps the token; a stale worker result is
  // dropped (the worker itself keeps computing until done — accepted waste).
  if (!forceMain && workerOn() && workerSupports(preset)) {
    const wOpts = { ...opts, animate: false }; // worker can't animate (no main-thread machinery)
    delete wOpts.animationDuration; delete wOpts.animationEasing;
    delete wOpts.eles; // the visible-only subset is passed separately — a cytoscape collection can't be postMessage'd (it would blow up the JSON clone and drop every other option)
    setLayoutIndicator(true, `Arranging · ${opts.name} (worker)…`);
    startProgressBar(preset);
    markLayoutStart(); // ⏱ last-layout readout
    startLayoutPill(); // live elapsed in the pill
    runWorkerLayout(preset, wOpts, 120000, visibleOnly ? cy.elements(':visible') : null).then(res => {
      if (jobToken !== workerRunToken()) return; // superseded — drop the stale result
      if (res && res.type === 'done' && isSaneSnapshot(res.positions)) {
        usingSavedPositions = false; usingCustomPositions = false; usingCuratedPositions = false;
        const placed = visibleOnly ? cy.nodes(':visible') : cy.nodes();
        cy.batch(() => {
          for (const n of placed) {
            const p = res.positions[n.id()];
            if (p) n.position({ x: p.x, y: p.y });
          }
        });
        activeLayout = null;
        layoutRunning = false;
        setLayoutIndicator(false);
        stopProgressBar(preset, true); // worker durations feed the same EMA
        recordLayoutDone(layoutElapsed(), (visibleOnly ? cy.nodes(':visible') : cy.nodes()).length); // ⏱ header readout
        hideVeil();
        if (!isolatedRoot) cy.fit(undefined, 60);
        updateReadout();
        if (pendingSave && pendingSave.preset === preset) {
          const p = pendingSave; pendingSave = null;
          doCustomSave(p.preset, lastSpacing, p.dens);
        }
      } else {
        const why = res && res.type === 'done' ? 'returned a degenerate result' : ((res && res.message) || 'failed');
        toast(`Worker layout ${why} — running on the main thread`);
        // reflow:false — this is a continuation of the current request, not a new
        // automatic reflow; without it the fallback would be dropped by the gate
        // whenever "re-layout on graph change" is off and the layout would hang
        runLayout(preset, { skipSaved: true, forceMain: true, visibleOnly, reflow: false });
      }
    });
    return;
  }
  setLayoutIndicator(true, `Arranging · ${opts.name}${FORCE_LAYOUTS.has(preset) ? (forceDir ? ' · force' : ' · spread') : ''}…`);
  startProgressBar(preset); // live progress in the Arranging pill (time-calibrated)
  markLayoutStart(); // ⏱ last-layout readout — starts at the same point
  startLayoutPill(); // live elapsed in the pill
  // snapshot positions so we can detect algorithms that silently no-op
  // (e.g. elk-radial needs a rooted/tree graph — degenerate on the full DAG).
  // visibleOnly runs move just the visible subgraph, so sample the targets.
  const targets = opts.eles || cy.nodes();
  const before = new Map(targets.map(n => [n.id(), n.position()]));
  // a superseded async layout that finishes late would otherwise write its stale
  // positions over this run's fresh ones (layoutstop fires only afterwards).
  // Once superseded, the transform returns each node's CURRENT position — a no-op.
  opts.transform = (n, pos) => (myRunSeq === layoutRunSeq ? pos : n.position());
  const lay = cy.layout(opts);
  activeLayout = lay;
  lay.one('layoutstop', () => {
    if (activeLayout !== lay) return; // superseded by a newer layout
    activeLayout = null;
    layoutRunning = false;
    usingSavedPositions = false;
    setLayoutIndicator(false);
    stopProgressBar(preset, true); // record duration → EMA refines the bar each run
    recordLayoutDone(layoutElapsed(), cy.nodes(':visible').length); // ⏱ header readout
    hideVeil();
    if (!isolatedRoot) cy.fit(undefined, 60);
    updateReadout();
    // 💾 armed during the run? capture now — positions are final (P3-1b)
    if (pendingSave && pendingSave.preset === preset) {
      const p = pendingSave; pendingSave = null;
      doCustomSave(p.preset, lastSpacing, p.dens);
    }
    // warn when an algorithm leaves the graph untouched
    let moved = 0;
    const sample = targets.length > 300 ? targets.slice(0, 300) : targets;
    for (const n of sample) {
      const b = before.get(n.id());
      if (b && (Math.abs(b.x - n.position().x) + Math.abs(b.y - n.position().y)) > 1) { moved++; break; }
    }
    if (!moved && targets.length > 1) toast(`${preset} made no changes here — it needs a tree/rooted subgraph. Isolate a subtree first, or pick another layout.`);
  });
  lay.run();
}
